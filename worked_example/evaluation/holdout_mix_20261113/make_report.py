def f1(x):
    return f"{x:.1f}"


def sgn(x):
    return ("+" if x >= 0 else "−") + f"{abs(x):.2f}"


def span(d):
    return f"{sgn(d[0])}（{sgn(d[1])}〜{sgn(d[2])}）"


def g(st, grp):
    return A[str(st)]["groups"][grp]


def names(d, k=8):
    items = list(d.items())
    s = "、".join(f"{JA.get(c, c)} {n}" for c, n in items[:k])
    rest = sum(n for _, n in items[k:])
    return s + (f"、そのほか {rest}" if rest else "")


def gold_row(gname, fn, label="タヌキ"):
    rows = list(csv.reader(open(f"{GOLD}/{fn}_{gname}.csv", encoding="utf-8-sig")))
    head = rows[0]
    r = next(x for x in rows[1:] if x[0] == label)
    return head, r


def gold_pct(gname, fn, model):
    head, r = gold_row(gname, fn)
    j = next(i for i, h in enumerate(head) if h.replace("　", " ").startswith(model) and "正解" in h)
    return float(r[j + 1]), int(r[j]), int(r[1])


def gold_matrix(gname, model):
    rows = list(csv.reader(open(f"{GOLD}/matrix_{gname}_{model}.csv", encoding="utf-8-sig")))
    head = rows[0]
    r = next(x for x in rows[1:] if x[0] == "タヌキ")
    d = {head[i]: int(r[i]) for i in range(1, len(r)) if r[i].isdigit() and int(r[i]) and head[i] != "本数"}
    return dict(sorted(d.items(), key=lambda x: -x[1]))


